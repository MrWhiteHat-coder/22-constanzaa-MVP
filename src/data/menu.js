// ── helpers ─────────────────────────────────────────────────
export const getDish = (id) => dishes.find((d) => d.id === id)
export const categoryOf = (id) => categories.find((c) => c.id === id)
export const activeCategories = () =>
  categories.filter((c) => c.id === 'all' || dishes.some((d) => d.category === c.id))
export const relatedDishes = (dish, n = 3) =>
  dishes
    .filter((d) => d.available && d.category === dish.category && d.id !== dish.id)
    .slice(0, n)
export const signatureDishes = () => dishes.filter((d) => d.available && d.signature)
